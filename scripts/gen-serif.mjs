// Serif letter stamp pack generator — A–Z + a–z in PT Serif Bold as SVG stamp assets
// (#2002, FIELD stamps slice 3). Bakes glyph outlines from PT Serif Bold (SIL Open Font
// License 1.1; ParaType — https://github.com/googlefonts/ptserif) into path data on the
// 100x100 viewBox convention, on the letterform bake's reference (the face's own 'H'
// cap height ~80 units). This is the ONE contrasting serif face: normal proportions
// and bracketed serifs against Anton's condensed grotesque — Whittier's book face,
// dealt only when the Director calls the serif face (poets/fieldForm.js). The font
// FILE is never committed — only path data lands in the repo. Run from the repo root:
//   node scripts/gen-serif.mjs [/path/to/PTSerif-Bold.ttf]
// Pinned fetch (Google Fonts, v19 TTF): https://fonts.gstatic.com/s/ptserif/v19/EJRSQgYoZZY2vCFuvAnt65qV.ttf
// Requires the opentype.js devDependency (app/package.json).
//
// These are POEM-ONLY stamps (FIELD): catalogue members after the authored bake,
// excluded by id on every dealing surface — see poets/placement.js (SERIF_STAMP_IDS,
// POEM_ONLY_STAMP_IDS). Letter stamps are face-bound: a serif stamp is honest only
// inside a serif-declared form under Whittier (greenleaf); digits and punctuation
// stamps are face-shared and are NOT duplicated here.
import { readFileSync, writeFileSync } from 'node:fs';
import { parse } from '../app/node_modules/opentype.js/dist/opentype.mjs';

const FONT_PATH = process.argv[2] || '/tmp/PTSerif-Bold.ttf';
const TARGET_H = 80; // cap height in viewBox units — the letterforms' convention
const FS = 1000; // source raster size for precision

const r2 = (n) => Math.round(n * 100) / 100;

function transformCommands(commands, cx, cy, s) {
  const t = (x, y) => [r2((x - cx) * s + 50), r2((y - cy) * s + 50)];
  let d = '';
  for (const c of commands) {
    if (c.type === 'M' || c.type === 'L') {
      const [x, y] = t(c.x, c.y);
      d += `${c.type}${x} ${y}`;
    } else if (c.type === 'C') {
      const [x1, y1] = t(c.x1, c.y1);
      const [x2, y2] = t(c.x2, c.y2);
      const [x, y] = t(c.x, c.y);
      d += `C${x1} ${y1} ${x2} ${y2} ${x} ${y}`;
    } else if (c.type === 'Q') {
      const [x1, y1] = t(c.x1, c.y1);
      const [x, y] = t(c.x, c.y);
      d += `Q${x1} ${y1} ${x} ${y}`;
    } else if (c.type === 'Z') {
      d += 'Z';
    } else {
      throw new Error(`unsupported path command: ${c.type}`);
    }
  }
  return d;
}

const LETTERS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz';

const font = parse(readFileSync(FONT_PATH));
// Reference cap height from the serif's own 'H' — the letterform convention, so
// 1 em of serif cap height equals 1 em of Anton cap height on the dish.
const refBox = font.getPath('H', 0, 0, FS).getBoundingBox();
const scale = TARGET_H / (refBox.y2 - refBox.y1);

const entries = [];
function bake(ch) {
  const glyph = font.charToGlyph(ch);
  if (!glyph || glyph.index === 0) throw new Error(`font has no glyph: ${ch}`);
  const path = font.getPath(ch, 0, 0, FS);
  const bb = path.getBoundingBox();
  if (!(bb.x2 > bb.x1) || !(bb.y2 > bb.y1)) throw new Error(`empty glyph: ${ch}`);
  const cx = (bb.x1 + bb.x2) / 2;
  const cy = (bb.y1 + bb.y2) / 2;
  const d = transformCommands(path.commands, cx, cy, scale);
  // One property per line — the letterform pack's (prettier-clean) shape, so a
  // regen lands format:check-clean with no follow-up pass.
  entries.push(
    `  {\n` +
      `    id: 'typ_s_${ch}',\n` +
      `    category: 'geometric',\n` +
      `    tags: ['type', 'letter', 'serif'],\n` +
      `    weight: 'medium',\n` +
      `    density: 'solid',\n` +
      `    scale: [0.3, 1.2],\n` +
      `    rotate: 'free',\n` +
      `    glyph: '${ch}',\n` +
      `    svg: \`<path d="${d}" fill="var(--ink)"/>\`,\n` +
      `  },`,
  );
}

for (const ch of LETTERS) bake(ch);

const out = `// Serif letter stamp pack — A–Z + a–z in PT Serif Bold, POEM-ONLY (FIELD stamps slice 3, #2002).
// Generated by scripts/gen-serif.mjs — edit the generator, not this file.
// Glyph outlines baked from PT Serif Bold (SIL Open Font License 1.1,
// Copyright 2011 The PT Serif Project Authors, https://github.com/googlefonts/ptserif).
// The font file itself is NOT shipped; only path data is committed. Each glyph is
// centered on the 100x100 viewBox, cap height ~80 units on the face's own 'H'
// reference — the letterform pack's convention, so a serif em and an Anton em are
// the same cap height on the dish. Path data (never <text>), so every raster of
// these stamps is font-independent (#1970). The face is Whittier's alone: letter
// stamps are face-bound, digits and punctuation are face-shared (the base packs
// serve them in a serif form unchanged).
// Colors: var(--ink) primary (var(--accent) resolves at bake for tint combos).
export const ASSETS_SERIF = [\n${entries.join('\n')}\n];\n`;

writeFileSync('app/src/data/assets/assets-serif.js', out);
console.log('wrote', entries.length, 'serif assets');
