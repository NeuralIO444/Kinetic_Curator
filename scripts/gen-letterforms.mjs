// Letterform pack generator — A–Z 0–9 as SVG stamp assets.
// Bakes glyph outlines from Anton (SIL Open Font License 1.1;
// https://github.com/googlefonts/AntonFont) into path data on the
// 100x100 viewBox convention. The font FILE is never committed — only
// path data lands in the repo. Run from the repo root:
//   node scripts/gen-letterforms.mjs [/path/to/Anton-Regular.ttf]
// Requires the opentype.js devDependency (app/package.json).
import { readFileSync, writeFileSync } from 'node:fs';
import { parse } from '../app/node_modules/opentype.js/dist/opentype.mjs';

const FONT_PATH = process.argv[2] || '/tmp/Anton-Regular.ttf';
const CHARS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789';
const TARGET_H = 80; // cap height in viewBox units
const FS = 1000; // source raster size for precision

const r2 = (n) => Math.round(n * 100) / 100;

function transformCommands(commands, cx, cy, s) {
  const t = (x, y) => [r2((x - cx) * s + 50), r2((y - cy) * s + 50)];
  let d = '';
  for (const c of commands) {
    if (c.type === 'M' || c.type === 'L') {
      const [x, y] = t(c.x, c.y);
      d += `${c.type}${x} ${y}`;
    } else if (c.type === 'C') {
      const [x1, y1] = t(c.x1, c.y1);
      const [x2, y2] = t(c.x2, c.y2);
      const [x, y] = t(c.x, c.y);
      d += `C${x1} ${y1} ${x2} ${y2} ${x} ${y}`;
    } else if (c.type === 'Q') {
      const [x1, y1] = t(c.x1, c.y1);
      const [x, y] = t(c.x, c.y);
      d += `Q${x1} ${y1} ${x} ${y}`;
    } else if (c.type === 'Z') {
      d += 'Z';
    } else {
      throw new Error(`unsupported path command: ${c.type}`);
    }
  }
  return d;
}

const font = parse(readFileSync(FONT_PATH));
// Reference cap height from 'H' so every glyph keeps its true relative size.
const refBox = font.getPath('H', 0, 0, FS).getBoundingBox();
const scale = TARGET_H / (refBox.y2 - refBox.y1);

const entries = [];
for (const ch of CHARS) {
  const path = font.getPath(ch, 0, 0, FS);
  const bb = path.getBoundingBox();
  if (!(bb.x2 > bb.x1) || !(bb.y2 > bb.y1)) throw new Error(`empty glyph: ${ch}`);
  const cx = (bb.x1 + bb.x2) / 2;
  const cy = (bb.y1 + bb.y2) / 2;
  const d = transformCommands(path.commands, cx, cy, scale);
  const isDigit = ch >= '0' && ch <= '9';
  const id = `typ_${ch}`;
  const tags = isDigit ? ['type', 'digit'] : ['type', 'letter'];
  entries.push(
    `  { id: '${id}', category: 'geometric', tags: [${tags.map((t) => `'${t}'`).join(', ')}], weight: 'medium', density: 'solid', scale: [0.3, 1.2], rotate: 'free',\n` +
    `    svg: \`<path d="${d}" fill="var(--ink)"/>\` },`
  );
}

const out = `// Letterform stamp pack — A–Z 0–9 in a bold condensed grotesque.
// Generated by scripts/gen-letterforms.mjs — edit the generator, not this file.
// Glyph outlines baked from Anton (SIL Open Font License 1.1,
// Copyright 2020 The Anton Project Authors, https://github.com/googlefonts/AntonFont).
// The font file itself is NOT shipped; only path data is committed.
// Each glyph is centered on the 100x100 viewBox, cap height ~80 units.
// Colors: var(--ink) primary (var(--accent) resolves at bake for tint combos).
export const ASSETS_LETTERS = [\n${entries.join('\n')}\n];\n`;

writeFileSync('app/src/data/assets/assets-letterforms.js', out);
console.log('wrote', entries.length, 'letterform assets');
