// Latin lowercase + punctuation stamp pack generator — Anton a–z and the punctuation set
// as SVG stamp assets (#2002, FIELD stamps slice 3). Bakes glyph outlines from Anton
// (SIL Open Font License 1.1; https://github.com/googlefonts/AntonFont) into path data on
// the 100x100 viewBox convention, exactly as scripts/gen-letterforms.mjs does for the caps
// pack — and on the SAME reference (the 'H' cap height), so lowercase sits at its true
// relative size beside the caps. Anton's lowercase is genuinely drawn (verified at bake
// time, #2002: every a–z maps to its own glyph with an outline distinct from the cap's,
// at x-height metrics — not .notdef, not remapped caps). The font FILE is never committed
// — only path data lands in the repo. Run from the repo root:
//   node scripts/gen-latin.mjs [/path/to/Anton-Regular.ttf]
// Pinned fetch (google/fonts): https://raw.githubusercontent.com/google/fonts/main/ofl/anton/Anton-Regular.ttf
// Requires the opentype.js devDependency (app/package.json).
//
// These are POEM-ONLY stamps (FIELD): they join the catalogue after the authored bake
// (data/assets/index.js) so the census and the stage atlas resolve them, and every
// dealing surface excludes them by id — see poets/placement.js (LATIN_STAMP_IDS,
// POEM_ONLY_STAMP_IDS). The punctuation set is the issue's declared list, complete:
// every glyph was probe-verified present in Anton with real ink, so nothing is trimmed.
import { readFileSync, writeFileSync } from 'node:fs';
import { parse } from '../app/node_modules/opentype.js/dist/opentype.mjs';

const FONT_PATH = process.argv[2] || '/tmp/Anton-Regular.ttf';
const TARGET_H = 80; // cap height in viewBox units — the letterforms' convention
const FS = 1000; // source raster size for precision

const r2 = (n) => Math.round(n * 100) / 100;

function transformCommands(commands, cx, cy, s) {
  const t = (x, y) => [r2((x - cx) * s + 50), r2((y - cy) * s + 50)];
  let d = '';
  for (const c of commands) {
    if (c.type === 'M' || c.type === 'L') {
      const [x, y] = t(c.x, c.y);
      d += `${c.type}${x} ${y}`;
    } else if (c.type === 'C') {
      const [x1, y1] = t(c.x1, c.y1);
      const [x2, y2] = t(c.x2, c.y2);
      const [x, y] = t(c.x, c.y);
      d += `C${x1} ${y1} ${x2} ${y2} ${x} ${y}`;
    } else if (c.type === 'Q') {
      const [x1, y1] = t(c.x1, c.y1);
      const [x, y] = t(c.x, c.y);
      d += `Q${x1} ${y1} ${x} ${y}`;
    } else if (c.type === 'Z') {
      d += 'Z';
    } else {
      throw new Error(`unsupported path command: ${c.type}`);
    }
  }
  return d;
}

const LOWERCASE = 'abcdefghijklmnopqrstuvwxyz';
// [glyph, slug] — the declared punctuation set (#2002). Typographic quotes, both
// dashes, the ellipsis: the orthography the decks' sentence face is written in.
const PUNCT = [
  ['.', 'period'],
  [',', 'comma'],
  [';', 'semicolon'],
  [':', 'colon'],
  ['!', 'bang'],
  ['?', 'quest'],
  ['‘', 'lsquo'],
  ['’', 'rsquo'],
  ['“', 'ldquo'],
  ['”', 'rdquo'],
  ['-', 'hyphen'],
  ['–', 'endash'],
  ['—', 'emdash'],
  ['&', 'amp'],
  ['…', 'ellipsis'],
  ['(', 'lparen'],
  [')', 'rparen'],
];

const font = parse(readFileSync(FONT_PATH));
// Reference cap height from 'H' — the SAME reference scripts/gen-letterforms.mjs
// bakes the caps to, so the lowercase keeps its true relative size against them.
const refBox = font.getPath('H', 0, 0, FS).getBoundingBox();
const scale = TARGET_H / (refBox.y2 - refBox.y1);

const entries = [];
function bake(ch, id, tags) {
  const glyph = font.charToGlyph(ch);
  if (!glyph || glyph.index === 0) throw new Error(`font has no glyph: ${ch} (${id})`);
  const path = font.getPath(ch, 0, 0, FS);
  const bb = path.getBoundingBox();
  if (!(bb.x2 > bb.x1) || !(bb.y2 > bb.y1)) throw new Error(`empty glyph: ${ch}`);
  const cx = (bb.x1 + bb.x2) / 2;
  const cy = (bb.y1 + bb.y2) / 2;
  const d = transformCommands(path.commands, cx, cy, scale);
  // One property per line — the letterform pack's (prettier-clean) shape, so a
  // regen lands format:check-clean with no follow-up pass.
  entries.push(
    `  {\n` +
      `    id: '${id}',\n` +
      `    category: 'geometric',\n` +
      `    tags: [${tags.map((t) => `'${t}'`).join(', ')}],\n` +
      `    weight: 'medium',\n` +
      `    density: 'solid',\n` +
      `    scale: [0.3, 1.2],\n` +
      `    rotate: 'free',\n` +
      `    glyph: '${ch}',\n` +
      `    svg: \`<path d="${d}" fill="var(--ink)"/>\`,\n` +
      `  },`,
  );
}

for (const ch of LOWERCASE) bake(ch, `typ_l_${ch}`, ['type', 'letter', 'lowercase']);
for (const [ch, slug] of PUNCT) bake(ch, `typ_p_${slug}`, ['type', 'punct']);

const out = `// Latin lowercase + punctuation stamp pack — Anton a–z and the punctuation set,
// POEM-ONLY (FIELD stamps slice 3, #2002).
// Generated by scripts/gen-latin.mjs — edit the generator, not this file.
// Glyph outlines baked from Anton (SIL Open Font License 1.1,
// Copyright 2020 The Anton Project Authors, https://github.com/googlefonts/AntonFont).
// The font file itself is NOT shipped; only path data is committed. Each glyph is
// centered on the 100x100 viewBox and baked on the caps pack's own reference (the
// 'H' cap height ~80 units), so lowercase sits at true relative size beside the
// caps and punctuation keeps its drawn proportions. Path data (never <text>), so
// every raster of these stamps is font-independent: the census confirms them with
// the bake's pinned-font raster exactly as it does the caps (#1970).
// 26 lowercase + 17 punctuation (the declared set, complete — every glyph verified
// present in Anton; nothing trimmed).
// Colors: var(--ink) primary (var(--accent) resolves at bake for tint combos).
export const ASSETS_LATIN = [\n${entries.join('\n')}\n];\n`;

writeFileSync('app/src/data/assets/assets-latin.js', out);
console.log('wrote', entries.length, 'latin assets');
