// Ornament stamp pack generator — plate-break ornaments as SVG stamp assets
// (#2002, FIELD stamps slice 3). Bakes glyph outlines from PT Serif Bold (SIL Open
// Font License 1.1; ParaType) — the slice's book face, whose printer's furniture
// these are — into path data on the 100x100 viewBox convention, on the serif bake's
// reference (the face's 'H' cap height ~80 units) so an ornament sits at its true
// relative size beside the type. The font FILE is never committed — only path data
// lands in the repo. Run from the repo root:
//   node scripts/gen-ornaments.mjs [/path/to/PTSerif-Bold.ttf]
// Pinned fetch (Google Fonts, v19 TTF): https://fonts.gstatic.com/s/ptserif/v19/EJRSQgYoZZY2vCFuvAnt65qV.ttf
// Requires the opentype.js devDependency (app/package.json).
//
// The set is what the bake font covers, with per-glyph causes (#2002):
//   § section mark, ¶ pilcrow, † dagger, ‡ double dagger — the classic
//   plate-break furniture, all present in PT Serif Bold with real ink.
//   The fleuron (❦/❧/☙) and the asterism (⁂) are ABSENT from both bake fonts
//   (PT Serif and Anton) — dropped, not substituted from a third face.
//   The long dash is NOT duplicated here: — already ships as the face-shared
//   punctuation stamp (typ_p_emdash), and a second stamp id for the same glyph
//   would make the char-keyed resolver (poets/placement.js) ambiguous.
// Ornaments are POEM-ONLY and BREAK-ONLY: admissible in a Latin-face form only
// as a standalone plate-break stamp — its own segment between lines, never
// glyph-adjacent inside a line — and refused in native forms (poets/fieldForm.js).
import { readFileSync, writeFileSync } from 'node:fs';
import { parse } from '../app/node_modules/opentype.js/dist/opentype.mjs';

const FONT_PATH = process.argv[2] || '/tmp/PTSerif-Bold.ttf';
const TARGET_H = 80; // cap height in viewBox units — the letterforms' convention
const FS = 1000; // source raster size for precision

const r2 = (n) => Math.round(n * 100) / 100;

function transformCommands(commands, cx, cy, s) {
  const t = (x, y) => [r2((x - cx) * s + 50), r2((y - cy) * s + 50)];
  let d = '';
  for (const c of commands) {
    if (c.type === 'M' || c.type === 'L') {
      const [x, y] = t(c.x, c.y);
      d += `${c.type}${x} ${y}`;
    } else if (c.type === 'C') {
      const [x1, y1] = t(c.x1, c.y1);
      const [x2, y2] = t(c.x2, c.y2);
      const [x, y] = t(c.x, c.y);
      d += `C${x1} ${y1} ${x2} ${y2} ${x} ${y}`;
    } else if (c.type === 'Q') {
      const [x1, y1] = t(c.x1, c.y1);
      const [x, y] = t(c.x, c.y);
      d += `Q${x1} ${y1} ${x} ${y}`;
    } else if (c.type === 'Z') {
      d += 'Z';
    } else {
      throw new Error(`unsupported path command: ${c.type}`);
    }
  }
  return d;
}

// [glyph, slug] — the covered plate-break furniture of the bake font.
const ORNAMENTS = [
  ['§', 'sect'],
  ['¶', 'pilcrow'],
  ['†', 'dagger'],
  ['‡', 'ddagger'],
];

const font = parse(readFileSync(FONT_PATH));
// Reference cap height from 'H' — the serif bake's reference, so the ornaments
// keep their true relative size against the serif type they break between.
const refBox = font.getPath('H', 0, 0, FS).getBoundingBox();
const scale = TARGET_H / (refBox.y2 - refBox.y1);

const entries = [];
function bake(ch, slug) {
  const glyph = font.charToGlyph(ch);
  if (!glyph || glyph.index === 0) throw new Error(`font has no glyph: ${ch} (typ_o_${slug})`);
  const path = font.getPath(ch, 0, 0, FS);
  const bb = path.getBoundingBox();
  if (!(bb.x2 > bb.x1) || !(bb.y2 > bb.y1)) throw new Error(`empty glyph: ${ch}`);
  const cx = (bb.x1 + bb.x2) / 2;
  const cy = (bb.y1 + bb.y2) / 2;
  const d = transformCommands(path.commands, cx, cy, scale);
  // One property per line — the letterform pack's (prettier-clean) shape, so a
  // regen lands format:check-clean with no follow-up pass.
  entries.push(
    `  {\n` +
      `    id: 'typ_o_${slug}',\n` +
      `    category: 'geometric',\n` +
      `    tags: ['type', 'ornament'],\n` +
      `    weight: 'medium',\n` +
      `    density: 'solid',\n` +
      `    scale: [0.3, 1.2],\n` +
      `    rotate: 'free',\n` +
      `    glyph: '${ch}',\n` +
      `    svg: \`<path d="${d}" fill="var(--ink)"/>\`,\n` +
      `  },`,
  );
}

for (const [ch, slug] of ORNAMENTS) bake(ch, slug);

const out = `// Ornament stamp pack — plate-break furniture (§ ¶ † ‡) in PT Serif Bold,
// POEM-ONLY and BREAK-ONLY (FIELD stamps slice 3, #2002).
// Generated by scripts/gen-ornaments.mjs — edit the generator, not this file.
// Glyph outlines baked from PT Serif Bold (SIL Open Font License 1.1,
// Copyright 2011 The PT Serif Project Authors, https://github.com/googlefonts/ptserif).
// The font file itself is NOT shipped; only path data is committed. Each glyph is
// centered on the 100x100 viewBox and baked on the serif face's 'H' reference
// (cap height ~80 units), so an ornament sits at true relative size. Path data
// (never <text>), so every raster is font-independent (#1970). An ornament is
// admissible only as a standalone plate break between a poem's lines — never
// inside a line, never in a native form (poets/fieldForm.js).
// Colors: var(--ink) primary (var(--accent) resolves at bake for tint combos).
export const ASSETS_ORNAMENTS = [\n${entries.join('\n')}\n];\n`;

writeFileSync('app/src/data/assets/assets-ornaments.js', out);
console.log('wrote', entries.length, 'ornament assets');
