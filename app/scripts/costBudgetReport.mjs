// costBudgetReport.mjs — #1639: the corpus-vs-budget report.
//
//   node scripts/costBudgetReport.mjs --in <cost-dataset.json> [--out docs/COST_BUDGETS.md] [--base grid-base]
//
// Consumes a costBench dataset (src/gl/parity/costBench.mjs) and writes the report the issue asks
// for: both frame budgets (src/data/quality.js FRAME_BUDGETS), every recipe's measured label
// judged against both, every bust named, the near-busts named, and the recipes the harness could
// not measure in its environment named with their errors — never dropped, never called busts.
//
// The dataset's environment stamp leads the report. Verdicts are only as device-true as the
// environment that measured them: on a SwiftShader run the absolute labels are orders of
// magnitude off device truth, the verdict column describes that environment, and the portable
// content is the ordering and the spread over the base recipe (the ×base column). The same
// command on a Studio/device dataset produces the device-truth table with no code change.
import { readFileSync, writeFileSync } from 'node:fs';
import { FRAME_BUDGETS } from '../src/data/quality.js';
import { classifyDataset } from '../src/gl/parity/deviceBudgets.mjs';

const args = { in: null, out: null, base: 'grid-base' };
for (let i = 2; i < process.argv.length; i++) {
  if (process.argv[i] === '--in') args.in = process.argv[++i];
  else if (process.argv[i] === '--out') args.out = process.argv[++i];
  else if (process.argv[i] === '--base') args.base = process.argv[++i];
  else throw new Error(`unknown arg: ${process.argv[i]}`);
}
if (!args.in) throw new Error('--in <cost-dataset.json> is required');

const ds = JSON.parse(readFileSync(args.in, 'utf8'));
const c = classifyDataset(ds, args.base);
const env = c.environment || {};
const fmt = (x, d = 1) => (x === null || x === undefined ? '—' : x.toFixed(d));
const verdict = (v) => (v.verdict === 'unmeasured' ? 'unmeasured' : `${v.verdict} (${fmt(v.multiple, 2)}× cap)`);

const lines = [];
lines.push('# Corpus vs frame budgets (#1639)');
lines.push('');
lines.push(`Generated by \`scripts/costBudgetReport.mjs\` from a costBench dataset. The budgets are`);
lines.push(`\`FRAME_BUDGETS\` in \`src/data/quality.js\`; the labels are the harness's (median of per-repetition`);
lines.push(`p90 frame ms, readback-forced renderScene). Re-run the bench on device-class hardware and`);
lines.push(`re-run this script to refresh the table — the worked example at the end is authored and`);
lines.push(`must be re-walked when the heaviest recipe changes.`);
lines.push('');
lines.push('## The budgets');
lines.push('');
lines.push('| class | target | frame | render cap | near-bust from |');
lines.push('|---|---|---|---|---|');
for (const cls of ['desktop', 'ipad']) {
  const b = FRAME_BUDGETS[cls];
  lines.push(
    `| ${cls} | ${b.targetFps} fps | ${fmt(b.frameMs)} ms | ${fmt(b.renderCapMs)} ms | ${fmt(b.renderCapMs * b.nearBustRatio)} ms |`,
  );
}
lines.push('');
lines.push('## The evidence');
lines.push('');
lines.push(`- Renderer: \`${env.renderer || 'unknown'}\``);
lines.push(`- Software GL (SwiftShader): **${env.swiftShader ? 'yes' : 'no'}**`);
if (env.swiftShader) {
  lines.push('');
  lines.push('> This dataset was measured on software GL. Its absolute labels are orders of magnitude');
  lines.push('> slower than any device GPU, so the verdict columns describe THIS environment — read');
  lines.push('> them as the ordering and the spread (×base), never as device labels. The device-truth');
  lines.push('> table is this same report run on a dataset measured on Studio/device hardware.');
}
lines.push('');
lines.push('## The corpus against both budgets');
lines.push('');
lines.push(`| recipe | label (ms) | ×base | desktop | iPad |`);
lines.push('|---|---|---|---|---|');
for (const r of c.rows) {
  lines.push(`| ${r.id} | ${fmt(r.labelMs)} | ${fmt(r.overBase, 2)} | ${verdict(r.desktop)} | ${verdict(r.ipad)} |`);
}
lines.push('');
lines.push('## Named findings');
lines.push('');
lines.push(
  `- **Busts both budgets:** ${c.busts.desktop.filter((id) => c.busts.ipad.includes(id)).join(', ') || 'none'}`,
);
lines.push(
  `- **Desktop-only (busts iPad, fits or near on desktop):** ${c.busts.ipad.filter((id) => !c.busts.desktop.includes(id)).join(', ') || 'none'}`,
);
lines.push(
  `- **Near-busts:** desktop — ${c.nearBusts.desktop.join(', ') || 'none'}; iPad — ${c.nearBusts.ipad.join(', ') || 'none'}`,
);
const un = c.rows.filter((r) => r.desktop.verdict === 'unmeasured');
lines.push(
  `- **Unmeasured in this environment:** ${un.length ? un.map((r) => `${r.id} (${r.failed || 'no label'})`).join('; ') : 'none'}`,
);
lines.push('');

// #1694 S2 — the creature citizen's families. Not recipes in the dataset: per-family cost
// DECLARATIONS read from the cost registry (engine/kernel/costRegistry.mjs — the numbers live
// there, never hard-coded here), judged against the creature allowance inside the frame
// budgets (data/quality.js CREATURE_FRAME_ALLOWANCE_MS, spending from the iPad cap). The
// declarations are resolver-CPU measurements at each family's population cap, sandbox-labelled
// in the registry; the standing re-measurement proof is engine/kernel/creatureCost.selfcheck.mjs.
const { allCostTiers } = await import('../src/engine/kernel/costRegistry.mjs');
const { CREATURE_FRAME_ALLOWANCE_MS } = await import('../src/data/quality.js');
const nearBustFrom = CREATURE_FRAME_ALLOWANCE_MS * FRAME_BUDGETS.ipad.nearBustRatio;
const creatureVerdict = (ms) => (ms > CREATURE_FRAME_ALLOWANCE_MS ? 'BUST' : ms >= nearBustFrom ? 'near-bust' : 'ok');
const familyRows = ['creature/moth', 'creature/dish'].map((id) => {
  const d = allCostTiers().find((t) => t.id === id);
  if (!d) throw new Error(`cost registry is missing the citizen family declaration '${id}'`);
  return d;
});
lines.push('## Creatures — the citizen\u2019s families (registry declarations)');
lines.push('');
lines.push(
  `Allowance: **${fmt(CREATURE_FRAME_ALLOWANCE_MS, 2)} ms** at the population cap (near-bust from ${fmt(nearBustFrom, 2)} ms, the budgets' 80% rule).`,
);
lines.push('');
lines.push('| family | declared (ms) | share of allowance | verdict |');
lines.push('|---|---|---|---|');
for (const d of familyRows) {
  lines.push(
    `| ${d.id} | ${fmt(d.timeMs, 2)} | ${fmt((d.timeMs / CREATURE_FRAME_ALLOWANCE_MS) * 100, 0)}% | ${creatureVerdict(d.timeMs)} |`,
  );
}
const combinedMs = familyRows.reduce((s2, d) => s2 + d.timeMs, 0);
lines.push(
  `| both families at their own caps (conservative sum — the 4-pin cap means they cannot co-occur; the measured full stage is lower) | ${fmt(combinedMs, 2)} | ${fmt((combinedMs / CREATURE_FRAME_ALLOWANCE_MS) * 100, 0)}% | ${creatureVerdict(combinedMs)} |`,
);
lines.push('');
lines.push('## Worked example');
lines.push('');
lines.push('<!-- Authored in the committed report: name the heaviest measured recipe, its label against');
lines.push("     both caps, and what the governor's shed order would do about it, tier by tier. -->");
lines.push('');

const text = lines.join('\n');
if (args.out) {
  writeFileSync(args.out, text);
  console.log(`report: ${args.out} (${c.rows.length} recipes, base ${c.baseMs} ms)`);
} else {
  console.log(text);
}
