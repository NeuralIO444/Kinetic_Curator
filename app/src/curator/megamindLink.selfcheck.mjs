const jsonRes = (data, status = 200) => ({
  ok: status >= 200 && status < 300,
  status,
  json: async () => data,
});
function makeFetch(handler) {
  const calls = [];
  const fetchImpl = async (url, init = {}) => {
    calls.push({ url, init });
    return handler(url, init);
  };
  return { fetchImpl, calls };
}
/** A working fake Ollama serving the shelf; the chat call advances the injected clock by probeMs. */
function shelfFetch({
  probeMs = 1200,
  probeContent = '{"critique":null}',
  advance = () => {},
  tags = TAGS,
  shows = SHOWS,
} = {}) {
  return makeFetch((url, init) => {
    if (url.endsWith('/api/tags')) return jsonRes(tags);
    if (url.endsWith('/api/show')) {
      const { model } = JSON.parse(init.body);
      return shows[model] ? jsonRes(shows[model]) : jsonRes({ error: 'model not found' }, 404);
    }
    if (url.endsWith('/api/generate')) return jsonRes({ done: true, done_reason: 'load' });
    if (url.endsWith('/api/chat')) {
      advance(probeMs);
      return jsonRes({ message: { role: 'assistant', content: probeContent }, done: true });
    }
    throw new Error(`unexpected fetch ${url}`);
  });
}
const fakeStorage = (seed = {}) => {
  const map = new Map(Object.entries(seed));
  return {
    map,
    getItem: (k) => (map.has(k) ? map.get(k) : null),
    setItem: (k, v) => map.set(k, String(v)),
    removeItem: (k) => map.delete(k),
  };
};
function makeDriver(opts = {}) {
  let t = 1000;
  const advance = (ms) => {
    t += ms;
  };
  const shelf = shelfFetch({ advance, ...opts });
  const storage = opts.storage ?? fakeStorage();
  const driver = createLinkDriver({
    fetchImpl: shelf.fetchImpl,
    storage,
    now: () => t,
    stamp: () => 1760000000000,
    origin: 'https://kc1.example',
    userAgent: 'Mozilla/5.0 Chrome/126.0',
    isDesktop: () => false,
    ...(opts.driver ?? {}),
  });
  return { driver, calls: shelf.calls, storage };
}

