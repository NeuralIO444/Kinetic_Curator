const LETTERS = new Set(['stem','bowl','arch','fork','serif','counter','ligature','flag']);
const SPECKS = new Set(['speck','speck_ne','spark','dust']);

function svgFor(rows) {
  let s = '';
  rows.forEach((row, y) => {
    [...row].forEach((c, x) => {
      if (c === '0') return;
      const fill = c === '2' ? A : I;
      s += `<rect x="${ORIGIN + x * CELL}" y="${ORIGIN + y * CELL}" width="${CELL}" height="${CELL}" fill="${fill}"/>`;
    });
  });
  return s;
}

function entry(name) {
  const speck = SPECKS.has(name);
  const letter = LETTERS.has(name);
  return {
    id: `pxg_${name}`,
    category: speck ? 'dots' : 'stamps',
    tags: speck ? ['pixel', 'speck', 'star', 'modular'] : ['pixel', 'glyph', letter ? 'letter' : 'emblem', 'modular'],
    weight: speck ? 'light' : 'medium',
    density: 'sparse',
    scale: [0.22, 0.6],
    rotate: letter ? 'fixed' : 'free',
    svg: svgFor(GLYPHS[name]),
  };
}

export const ASSETS_PIXEL = Object.keys(GLYPHS).map(entry);
