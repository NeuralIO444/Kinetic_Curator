const records = assetRecords(ASSETS);
const hash = (s) => {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 16777619);
  return h >>> 0 || 1;
};
/** An S3-coherent pool of `n` assets for a family voice, drawn deterministically from the voice id. */
function familyPool(id, categories, styles, n = 8) {
  const ids = assetsWhere(records, { categories, styles }).sort();
  const rng = mkRng(hash(`voice:${id}`));
  const out = [];
  const left = [...ids];
  while (out.length < n && left.length) out.push(left.splice(Math.floor(rng() * left.length), 1)[0]);
  return out;
}
const toAssets = (ids) => Object.fromEntries(ids.map((id) => [id, true]));
const body = (mode, count, motionId, acc) => ({
  mode,
  count,
  particleCount: Math.min(count, 500),
  scale: [0.3, 1.3],
  rotate: [-90, 90],
  alpha: [55, 100],
  zTiers: 3,
  jitter: 12,
  density: 72,
  bleed: false,
  mirror: false,
  overlap: true,
  ...motion(motionId),
  ...acc,
});

const promoted = PROMOTED.map(([id, title, motionId, paletteId, categories, styles, count, acc, costTier, fx]) => {
  const stub = STUB_VOICES.find((v) => v.id === id);
  return {
    id,
    name: stub.name,
    title,
    vibe: stub.vibe,
    glyph: stub.glyph,
    kind: 'promoted',
    family: null,
    blendSeconds: 2,
    palette: sky(paletteId),
    paletteId,
    params: body(id, count, motionId, acc),
    fx: { grain: 0, vignette: false, posterize: false, edge: false, glow: 0, contrast: 1, ...fx },
    assets: toAssets(fullShapeSet(stub)),
    categories,
    styles,
    accumulation: acc.accumulation === true,
    costTier,
  };
});

const variants = Object.entries(VARIANTS).flatMap(([family, rows]) =>
  rows.map(([id, title, vibe, mode, motionId, paletteId, count, acc, costTier]) => ({
    id,
    name: id,
    title,
    vibe,
    glyph: family,
    kind: 'family',
    family,
    blendSeconds: 2,
    palette: sky(paletteId),
    paletteId,
    params: body(mode, count, motionId, acc),
    fx: { grain: family === 'grunge' ? 0.4 : 0, vignette: family === 'engraved', posterize: family === 'memphis' },
    assets: toAssets(familyPool(id, FAMILY_PAIRING[family], [family])),
    categories: FAMILY_PAIRING[family],
    styles: [family],
    accumulation: acc.accumulation === true,
    costTier,
  })),
);

const flagships = FLAGSHIP_VOICES.map((def) => ({
  def, // the flagship object itself — same reference, never cloned or edited
  kind: 'flagship',
  ...FLAGSHIP_META[def.id],
  accumulation: def.params.accumulation === true,
}));

/**
 * The deck: one record per dealable voice — `{ id, kind, def, categories, styles, accumulation, costTier }`. `def` is
 * a kc-voice/1 definition resolveVoiceState accepts; for a flagship it IS the FLAGSHIP_VOICES entry.
 */
export const VOICE_DECK = Object.freeze([
  ...flagships.map((f) => ({ id: f.def.id, ...f })),
  ...[...promoted, ...variants].map((def) => ({
    id: def.id,
    kind: def.kind,
    def,
    categories: def.categories,
    styles: def.styles,
    accumulation: def.accumulation,
    costTier: def.costTier,
  })),
]);

export const VOICE_DECK_COUNT = VOICE_DECK.length;

/** A deck voice by id (null when unknown). */
export function deckVoice(id) {
  return VOICE_DECK.find((v) => v.id === id) || null;
}
