// assets/assetTraitsBake.mjs — #1942: the Node bake of the measured traits (same canonical raster as the region bake).
import { Resvg } from '@resvg/resvg-js';
import { canonicalSvg } from './regionBake.mjs';
import { RESVG_FONT } from './resvgFont.mjs';
import { traitsFromRaster } from './assetTraits.js';

/** One asset's traits from the bundled-font Node raster. */
export function bakeAssetTraits(svg) {
  const r = new Resvg(canonicalSvg(svg), { font: RESVG_FONT }).render();
  return traitsFromRaster(r.pixels, r.width, r.height);
}

/** id → traits for a list of assets. */
export function bakeTraitsLibrary(assets) {
  const out = {};
  for (const a of assets) out[a.id] = bakeAssetTraits(a.svg);
  return out;
}

export function renderTraitsModule(baked) {
  const rows = Object.keys(baked)
    .sort()
    .map((id) => {
      const t = baked[id];
      const key = /^[A-Za-z_$][\w$]*$/.test(id) ? id : `'${id}'`; // prettier's quote-props: as-needed
      return `  ${key}: [${t.elong}, ${t.fill}, ${t.stroke}, ${t.sym}, ${t.busy}, ${t.mass}],`;
    });
  return `// GENERATED by scripts/bakeAssetTraits.mjs (npm run bake:traits) — do not edit. #1942\n// id -> [elong, fill, stroke, sym, busy, mass]\nexport const ASSET_TRAITS_ROWS = {\n${rows.join('\n')}\n};\n`;
}
