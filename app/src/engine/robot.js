// engine/robot.js — Phase 2 creature system, slice S6: the ROBOT type. RULES ONLY — this module forks
// nothing: it parameterises S1's skeleton builder (engine/skeleton.js) with robot plans, and post-processes
// the built bones with a pose quantiser and a mechanical settle. No new render path, no new engine; if the
// robot ever needs one, that is Matt's kill criterion for this slice, and the answer is to stop, not fork.
//
// The robot's law (Matt's Phase 2 rulings): its angles and moves are limited to 0°/45°/90° — every joint
// rests on a multiple of 45° (a DETENT), and a joint TRAVELS between detents mechanically over 2–3 counted
// frames (ruling 2: a short settle, not a hard snap, and not a spring — there is no clock here at all; the
// caller counts frames and the pose is a pure function of the frame index and the target sequence).
//
// What lives here, all of it data or pure functions of it:
//   - the detent quantiser (one angle, then a whole skeleton: spine + left chains snapped, the right side
//     re-mirrored from the snapped left, so mirror symmetry stays exact by construction);
//   - the settle: a per-joint segment state ({from, to, delta, start, frames}) the caller threads from
//     frame to frame; stepRobotPose() advances it toward the frame's quantised targets, and
//     settleRobotSkeleton() returns the posed skeleton for that frame;
//   - the 4x4x4 plan scheme for the robot (bodies = spine plans, limbs = wing-chain plans, hands =
//     ornament sets — the plan's vocabulary), drawn per creature from the seeded 'skeleton' stream;
//   - the plate + rivet part pool (procedural data, Davis-first: the parts are described, never drawn here);
//   - the panel-line hatch engraving variant, as DATA the engraving family (S4) keys on — no shader here.
//
// Space: everything operates on CREATURE-LOCAL skeletons, exactly as buildSkeleton returns them (the same
// space S1 proves the mirror in). Placement stays S1's transformSkeleton, applied afterwards by the caller.
//
// Cost: CPU-only rules. A quantise/settle pass is O(bones) arithmetic per creature per frame — no GPU pass,
// no draw, nothing to register in costRegistry; the 2.0 ms creature budget binds the render passes (S2–S4),
// not this file.
import { rngForIndex } from './kernel/rng.js';
import { buildSkeleton, mirrorBone, skeletonHash, fnv1a } from './skeleton.js';

const finite = (v, d) => (Number.isFinite(v) ? v : d);
const normDeg = (d) => (((d + 180) % 360) + 360) % 360 - 180;
const noNegZero = (v) => (v === 0 ? 0 : v);
const rad = (deg) => (deg * Math.PI) / 180;

/** The robot's detent step: every resting joint angle is a multiple of this. */
export const ROBOT_DETENT_STEP_DEG = 45;
/** Settle length for a move of one detent step or less (ruling 2: the settle runs 2–3 frames). */
export const ROBOT_SETTLE_FRAMES_NEAR = 2;
/** Settle length for a move longer than one detent step. */
export const ROBOT_SETTLE_FRAMES_FAR = 3;

/**
 * Snap one angle to the nearest detent (a multiple of 45°). Ties break toward the positive detent
 * (Math.round's half-up), so the rule is one arithmetic path with no hidden state. Lengths and scales are
 * NOT angles and are never quantised — a robot's sizes stay continuous; only its moves are mechanical.
 */
export function quantiseDetent(deg) {
  const d = normDeg(finite(deg, 0));
  return noNegZero(normDeg(Math.round(d / ROBOT_DETENT_STEP_DEG) * ROBOT_DETENT_STEP_DEG));
}

/** The shortest signed arc from one angle to another, in [-180, 180). Settle travel follows this arc. */
export function arcDeltaDeg(from, to) {
  return normDeg(finite(to, 0) - finite(from, 0));
}

const chainKeyOf = (id) => id.slice(0, id.lastIndexOf('/'));
const segIndexOf = (id) => Number(id.slice(id.lastIndexOf('/') + 1));

/**
 * Re-pose a creature-local skeleton with explicit absolute angles for its spine + left bones: each such
 * bone is rotated about its base to its given angle; a bone that grows out of its parent within the same
 * chain (its base was the parent's tip, by buildSkeleton's construction) is carried to the parent's new
 * tip, so chains stay joined; chain roots keep their attach-derived bases (a shoulder sits where the body
 * says it sits); lengths are preserved exactly. The right side is then re-derived with mirrorBone, so the
 * mirror is exact by construction at every pose, settled or mid-travel. `angleOf(bone)` returns degrees
 * for side 'C'/'L' bones. The source skeleton is untouched; the hash follows the new bones.
 */
function poseWithAngles(skel, angleOf) {
  const posed = new Map();
  const bones = [];
  const leftPosed = [];
  for (const b of skel.bones || []) {
    if (b.side === 'R') continue; // regenerated by mirror below
    const angleDeg = angleOf(b);
    const parent = b.parent ? posed.get(b.parent) : null;
    let base = b.base;
    if (parent && chainKeyOf(b.id) === chainKeyOf(b.parent) && segIndexOf(b.id) === segIndexOf(b.parent) + 1) {
      base = parent.tip; // a sequential bone starts where its parent now ends
    }
    const ux = Math.cos(rad(angleDeg));
    const uy = Math.sin(rad(angleDeg));
    const bone = {
      ...b,
      base: { x: base.x, y: base.y },
      tip: { x: base.x + ux * b.length, y: base.y + uy * b.length },
      ux, uy, angleDeg,
      localAngleDeg: parent ? normDeg(angleDeg - parent.angleDeg) : 0,
    };
    posed.set(b.id, bone);
    bones.push(bone);
    if (b.side === 'L') leftPosed.push(bone);
  }
  bones.push(...leftPosed.map(mirrorBone));
  const out = { ...skel, bones };
  out.hash = skeletonHash(out);
  return out;
}

/**
 * The pose quantiser: snap a built skeleton's every joint to its detent. Spine and chain angles land on
 * exact multiples of 45° (and so do the local joint angles, being differences of detents). One honest
 * consequence, and it is the type's whole look: the head bone's tip no longer lands exactly on the
 * artist's H point — for the robot, the detent wins over the landmark. (The moth keeps landmark
 * exactness; that difference is what makes this a different type and not a costume.)
 */
export function quantiseSkeletonPose(skel) {
  return poseWithAngles(skel, (b) => quantiseDetent(b.angleDeg));
}

/** The quantised target angles a raw built skeleton asks for: { boneId: detentDeg } for spine + left bones. */
export function robotTargetAngles(skel) {
  const targets = {};
  for (const b of (skel && skel.bones) || []) {
    if (b.side !== 'R') targets[b.id] = quantiseDetent(b.angleDeg);
  }
  return targets;
}

// --- the settle: joints travel between detents over counted frames -------------------------------------
//
// State is a plain value the caller threads through frames: { joints: { boneId: segment } }, a segment
// being { from, to, delta, start, frames } — the joint leaves `from` at frame `start`, follows the
// shortest arc `delta`, and is AT `to` from frame `start + frames` on. Nothing here reads a clock: the
// same (state, targets, frame) always gives the same pose, so a recorded take replays a robot exactly.

/** A fresh settle state: no joints yet. A joint with no segment is born settled on its first target. */
export function createRobotPoseState() {
  return { joints: {} };
}

/** One joint's angle at a frame under a segment; null when the joint has no segment. */
function segmentAngleAt(seg, frame) {
  if (!seg) return null;
  if (seg.frames <= 0 || frame >= seg.start + seg.frames) return seg.to;
  if (frame <= seg.start) return seg.from;
  return noNegZero(normDeg(seg.from + seg.delta * ((frame - seg.start) / seg.frames)));
}

/** The angle one joint shows at `frame` under `state`; null when the joint is unknown to the state. */
export function robotJointAngle(state, boneId, frame) {
  return segmentAngleAt(state && state.joints ? state.joints[boneId] : null, frame);
}

/**
 * Advance the settle one frame toward `targetAngles` ({ boneId: detentDeg }, from robotTargetAngles).
 * A joint whose target moved starts a new segment FROM WHERE IT STANDS at this frame (mid-travel
 * retargets included), lasting ROBOT_SETTLE_FRAMES_NEAR for a move of one detent step or less and
 * ROBOT_SETTLE_FRAMES_FAR for anything longer; a joint already travelling to the same target is left
 * undisturbed; a joint standing on its target settles instantly. Joints absent from the targets leave
 * the state (a chain that un-grows takes its joints with it). Pure: the input state is not mutated.
 */
export function stepRobotPose(state, targetAngles, frame) {
  const prev = (state && state.joints) || {};
  const joints = {};
  for (const [id, target] of Object.entries(targetAngles || {})) {
    const seg = prev[id];
    const cur = seg ? segmentAngleAt(seg, frame) : target;
    if (seg && seg.to === target) { joints[id] = seg; continue; }
    if (cur === target) { joints[id] = { from: target, to: target, delta: 0, start: frame, frames: 0 }; continue; }
    const delta = arcDeltaDeg(cur, target);
    joints[id] = {
      from: cur, to: target, delta, start: frame,
      frames: Math.abs(delta) <= ROBOT_DETENT_STEP_DEG ? ROBOT_SETTLE_FRAMES_NEAR : ROBOT_SETTLE_FRAMES_FAR,
    };
  }
  return { joints };
}

/**
 * Pose one frame: advance the settle toward the raw skeleton's quantised targets and return the posed
 * skeleton (the raw skeleton's lengths and bases, the settle's angles), the advanced state, and the
 * per-joint angles used. Frames must be counted in increasing order, one step per frame.
 */
export function settleRobotSkeleton(state, rawSkel, frame) {
  const targets = robotTargetAngles(rawSkel);
  const next = stepRobotPose(state, targets, frame);
  const angles = {};
  for (const id of Object.keys(targets)) angles[id] = segmentAngleAt(next.joints[id], frame);
  return { state: next, skeleton: poseWithAngles(rawSkel, (b) => angles[b.id]), angles };
}

