/**
 * Draw one robot's 4x4x4 indices from the seeded stream — half the RNG key is the creature, and the draws
 * ride the same 'skeleton' channel as the bones, so re-rolling SPATIAL re-draws the robot's plans with its
 * frame. Returns { spine, chains, ornaments }, each an index into the lists above.
 */
export function robotPlanIndices(seed, creatureId, seedOffsets = null) {
  const stream = rngForIndex(seed, 'skeleton', fnv1a(`${creatureId}:robot-plan`), seedOffsets);
  const pick = (n) => Math.min(n - 1, Math.floor(stream() * n));
  return {
    spine: pick(ROBOT_SPINE_PLANS.length),
    chains: pick(ROBOT_CHAIN_PLANS.length),
    ornaments: pick(ROBOT_ORNAMENT_SETS.length),
  };
}

/** Compose a full skeleton plan (buildSkeleton's shape) from a spine plan index and a chain plan index. */
export function robotPlan(spineIdx, chainIdx) {
  const sp = ROBOT_SPINE_PLANS[Math.min(ROBOT_SPINE_PLANS.length - 1, Math.max(0, Math.floor(finite(spineIdx, 0))))];
  const cp = ROBOT_CHAIN_PLANS[Math.min(ROBOT_CHAIN_PLANS.length - 1, Math.max(0, Math.floor(finite(chainIdx, 0))))];
  return Object.freeze({
    id: `robot/${sp.id}+${cp.id}`,
    spineSegments: sp.spineSegments,
    hindAlong: sp.hindAlong,
    chains: cp.chains,
  });
}

/**
 * Build one robot's skeleton in one shot: draw (or take) the plan indices, build with S1's builder, and
 * quantise the pose onto the detents. Returns { planIndices, plan, ornamentSet, skeleton } — the skeleton
 * is born settled on its detents; frame-by-frame travel between poses is settleRobotSkeleton's business.
 */
export function buildRobotSkeleton({ seed = 0, creatureId = 'r0', attach = null, pose = {}, seedOffsets = null, planIndices = null } = {}) {
  const idx = planIndices || robotPlanIndices(seed, creatureId, seedOffsets);
  const plan = robotPlan(idx.spine, idx.chains);
  const raw = buildSkeleton({ seed, creatureId, plan, attach, pose, seedOffsets });
  return { planIndices: idx, plan, ornamentSet: ROBOT_ORNAMENT_SETS[idx.ornaments], skeleton: quantiseSkeletonPose(raw) };
}

/**
 * Build and pose one frame of a robot: build the frame's raw skeleton from the pose, then settle it
 * toward its detents under the threaded state. Returns { state, skeleton, angles, planIndices } — feed
 * `state` back in next frame. This is the whole per-frame robot rule, and it is a pure function of
 * (state, seed, creature, attach, pose, frame).
 */
export function buildRobotFrame(state, { seed = 0, creatureId = 'r0', attach = null, pose = {}, seedOffsets = null, planIndices = null } = {}, frame = 0) {
  const idx = planIndices || robotPlanIndices(seed, creatureId, seedOffsets);
  const raw = buildSkeleton({ seed, creatureId, plan: robotPlan(idx.spine, idx.chains), attach, pose, seedOffsets });
  const { state: next, skeleton, angles } = settleRobotSkeleton(state, raw, frame);
  return { state: next, skeleton, angles, planIndices: idx };
}
